"""Generate the kernel's model table from the single boot-selector catalog.

Electrical entries below are separately sourced. Catalog membership and RAM
size never establish wiring. Unknown wiring retains its stick count but is not
silently assigned another model's pins.
"""
from pathlib import Path
import argparse
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "boot_selector"))
from reference_model import MODEL_CATALOG

# invert_mask describes the sign relative to increasing raw ADC, X/Y/Z/RUDDER.
# 35H uses the newer saved ROCKNIX joypad implementation, not the deleted old
# adc-joystick ranges. Its directions remain a candidate pending physical data.
# click_mask bit 0=L3, bit 1=R3. No-stick entries must never request this wiring.
WIRING = {
    "rg34xxsp": ("H700_WIRING_PI_MUX", 0x0f, 0x03),
    "rg35xxh": ("H700_WIRING_PI_MUX", 0x03, 0x03),
    "rgcubexx": ("H700_WIRING_PI_MUX", 0x03, 0x03),
    "rg40xxh": ("H700_WIRING_PI_MUX", 0x03, 0x03),
    "rg40xxv": ("H700_WIRING_PI_MUX", 0x03, 0x01),
    "rg35xxpro": ("H700_WIRING_PI_MUX", 0x03, 0x03),
}


def render():
    lines = ["/* Generated by generate_profiles.py; do not hand-edit. */",
             "static const struct h700_stick_profile h700_stick_profiles[] = {"]
    for model in MODEL_CATALOG:
        if not model.sticks:
            wiring, invert, clicks = "H700_WIRING_NONE", 0, 0
        else:
            wiring, invert, clicks = WIRING.get(
                model.model_id, ("H700_WIRING_UNVERIFIED", 0, (1 << model.sticks) - 1))
        lines.append('    {"%s", %d, %s, 0x%02x, 0x%02x},' %
                     (model.model_id, model.sticks, wiring, invert, clicks))
    return "\n".join(lines + ["};", ""])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = HERE / "h700_profile_table.h"
    expected = render()
    if args.check:
        if target.read_text(encoding="utf-8") != expected:
            raise SystemExit("generated model table differs from selector catalog")
    else:
        target.write_text(expected, encoding="utf-8", newline="\n")
    print("PASS: all %d canonical catalog models and stick counts" % len(MODEL_CATALOG))


if __name__ == "__main__":
    main()
